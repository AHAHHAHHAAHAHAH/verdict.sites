const engine: Record<Locale, EngineUI> = { en, it, de, fr, es, pl, sv };

export type UI = EngineUI & SiteStrings;

function isObject(v: unknown): v is Record<string, unknown> {
  return !!v && typeof v === 'object' && !Array.isArray(v);
}

// Site copy wins over engine copy; objects are merged key by key, arrays and strings replaced.
function merge<A extends Record<string, unknown>>(base: A, over: Record<string, unknown>): A {
  const out: Record<string, unknown> = { ...base };
  for (const [k, v] of Object.entries(over)) out[k] = isObject(v) && isObject(out[k]) ? merge(out[k] as Record<string, unknown>, v) : v;
  return out as A;
}

const cache = new Map<Locale, UI>();

export function t(lang: Locale): UI {
  let ui = cache.get(lang);
  if (!ui) {
    const site = (siteStrings as Partial<Record<Locale, SiteStrings>>)[lang];
    if (!site) throw new Error(`Site strings missing for "${lang}"`);
    ui = merge(engine[lang] as unknown as Record<string, unknown>, site as unknown as Record<string, unknown>) as unknown as UI;
    cache.set(lang, ui);
  }
  return ui;
}

export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => values[k] ?? `{${k}}`);
}
